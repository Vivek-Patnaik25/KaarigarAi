function deepMergeKeys(template, current, lang) {
  const result = {};
  for (const [key, val] of Object.entries(template)) {
    if (typeof val === 'object' && val !== null && !Array.isArray(val)) {
      result[key] = deepMergeKeys(val, current?.[key] || {}, lang);
    } else {
      if (current && current[key] !== undefined && current[key] !== '') {
        result[key] = current[key];
      } else {
        // Provide contextual native translation for missing keys
        result[key] = translateFallback(key, val, lang);
      }
    }
  }
  return result;
}

