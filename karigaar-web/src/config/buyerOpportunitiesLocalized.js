export function getLocalizedBuyerOpportunity(opp, language = 'en') {
  if (!opp) return opp
  const lang = language || 'en'
  const buyerId = opp.buyer_id || opp.id || ''

  // 1. Localize buyer type
  const rawType = opp.buyer_type || 'Boutique / Retailer'
  const localizedType = BUYER_TYPES_LOCALIZED[rawType]?.[lang] || BUYER_TYPES_LOCALIZED[rawType]?.en || rawType

  // 2. Localize description
  const localizedDesc = BUYER_DESCRIPTIONS_LOCALIZED[buyerId]?.[lang]
    || opp[`description_${lang}`]
    || BUYER_DESCRIPTIONS_LOCALIZED[buyerId]?.en
    || opp.description
    || ''

  // 3. Localize region preferences
  let localizedRegions = opp.region_preferences
  if (Array.isArray(opp.region_preferences)) {
    localizedRegions = opp.region_preferences.map(r => REGIONS_LOCALIZED[r]?.[lang] || r)
  } else if (typeof opp.region_preferences === 'string') {
    localizedRegions = REGIONS_LOCALIZED[opp.region_preferences]?.[lang] || opp.region_preferences
  }

  // 4. Localize match reason
  const isTerracotta = (opp.categories || []).includes('pottery_terracotta')
  const matchReason = isTerracotta
    ? (MATCH_REASONS_LOCALIZED.terracotta[lang] || MATCH_REASONS_LOCALIZED.terracotta.en)
    : (MATCH_REASONS_LOCALIZED.general[lang] || MATCH_REASONS_LOCALIZED.general.en)

  return {
    ...opp,
    buyer_type: localizedType,
    description: localizedDesc,
    region_preferences: localizedRegions,
    match_reason: matchReason,
  }
}
